#!/usr/bin/env bash

echo "=========================================="
echo "  DNS Lab with Routers - Starting"
echo "=========================================="
echo ""
echo "Starting Kathara lab (without opening terminals)..."
kathara lstart --noterminals

echo ""
echo "Configuring Wireshark container..."
# Connect Wireshark to all networks to see traffic across routers
kathara lconfig -n wireshark --add ROOT
kathara lconfig -n wireshark --add IT
kathara lconfig -n wireshark --add NET
kathara lconfig -n wireshark --add LINK_RI
kathara lconfig -n wireshark --add LINK_IN
kathara lconfig -n wireshark --add LINK_RN

echo ""
echo "=========================================="
echo "  Lab Started Successfully!"
